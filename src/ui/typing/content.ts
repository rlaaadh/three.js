/** 진행 정도에 따라 응원 문구 */
export function cheerFor(done: number, total: number, unit: string) {
  if (done === 0) return { title: '준비 완료!', text: '천천히 시작해 볼까요?' }
  if (done >= total) return { title: '다 했어요!', text: '오늘도 타닥타닥 수고했어요 🎉' }
  if (done * 2 >= total) return { title: `${done}번째 ${unit}!`, text: '잘하고 있어요! 절반을 넘겼어요!' }
  return { title: `${done}번째 ${unit}!`, text: '좋아요, 이 느낌 그대로!' }
}

export function shuffle<T>(items: T[]) {
  const copy = [...items]
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[copy[i], copy[j]] = [copy[j], copy[i]]
  }
  return copy
}
