--
-- category: 어느 라운드에 쓰는 낱말인지
--   'idiom' = 사자성어 (라운드 2~5는 이것만, 6부터는 다른 낱말과 섞여요)
--   앞으로 다른 종류를 넣고 싶으면 category만 새로 정해서 넣으면 돼요.

create table if not exists public.rain_words (
  id bigint generated always as identity primary key,
  word text not null check (char_length(btrim(word)) between 1 and 20),
  category text not null default 'idiom',
  created_at timestamptz not null default now(),
  unique (category, word)
);

-- 행 단위 권한(RLS): 브라우저(anon)에서는 읽기만
alter table public.rain_words enable row level security;

drop policy if exists "누구나 낱말 보기" on public.rain_words;
create policy "누구나 낱말 보기"
  on public.rain_words for select
  to anon, authenticated
  using (true);

grant select on public.rain_words to anon, authenticated;
revoke insert, update, delete on public.rain_words from anon, authenticated;

